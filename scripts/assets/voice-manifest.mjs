// Voice assets: scan public/assets/audio/voice/<character>/<line id>[.rough].ogg and write
// available.json (the runtime only fetches files listed there, so missing recordings never
// cause 404 noise). With --script, also regenerate docs/VOICE_RECORDING_SCRIPT.md from the
// game's own manifest (src/game/audio/voiceLines.ts), so text and recordings never drift.
// Usage: node scripts/assets/voice-manifest.mjs [--script]
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = 'public/assets/audio/voice';
const files = [];
function walk(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(ogg|mp3|m4a)$/i.test(name)) files.push(relative('public', p).split(String.fromCharCode(92)).join('/'));
  }
}
walk(ROOT);
// Credits are mandatory: a recording ships only if its character has a credits entry naming the
// performer (or the licensed voice source) and the licence. Nothing is presented as a human
// performance unless the credits say so.
const creditsPath = join(ROOT, 'credits.json');
const credits = existsSync(creditsPath) ? JSON.parse(readFileSync(creditsPath, 'utf8')) : [];
const credited = new Set(credits.filter((c) => c.character && c.performer && c.licence && ['human-recording', 'licensed-synthetic'].includes(c.source)).map((c) => c.character));
const shipped = [];
const rejected = [];
for (const f of files.sort()) (credited.has(f.split('/')[3]) ? shipped : rejected).push(f);
for (const f of rejected) console.warn(`voice: NOT listed (no credits entry for its character): ${f}`);
writeFileSync(join(ROOT, 'available.json'), JSON.stringify(shipped, null, 1) + '\n');
console.log(`voice: ${shipped.length} recorded file(s) listed (${rejected.length} rejected for missing credits)`);

if (process.argv.includes('--script')) {
  const { createServer } = await import('vite');
  const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
  try {
    const m = await server.ssrLoadModule('/src/game/audio/voiceLines.ts');
    const have = new Set(files);
    const byChar = new Map();
    const ordered = [...m.VOICE_LINES].sort((a, b) => m.recordingPriority(a) - m.recordingPriority(b));
    for (const l of ordered) {
      if (!byChar.has(l.character)) byChar.set(l.character, []);
      byChar.get(l.character).push(l);
    }
    const P = ['background', 'flavour', 'warning', 'must-hear'];
    let md = `# Voice recording script (generated)\n\nGenerated by \`npm run voice:script\` from \`src/game/audio/voiceLines.ts\` — do not edit by hand.\n\n`;
    md += `**${m.VOICE_LINES.length} lines**, ${files.length} recorded. Deliver each line as a separate mono file, 48 kHz, peak −3 dBFS, ~150 ms of room tone before and after, no music or effects; encode to Ogg Vorbis q5 at the exact path given. Record in the **Order** column (1 = first: thief, Rahim, Mojnu, chase shouts, the catch, then merchants, food and shop reactions). Extra takes for variety: \`<id>.2.ogg\` … \`<id>.4.ogg\`. **Every recorded character needs an entry in \`public/assets/audio/voice/credits.json\`** ({ character, performer, source: "human-recording" | "licensed-synthetic", licence, date }) — files without one are not shipped. Rough variants (\`.rough.ogg\`) only where a rough text is listed. After adding files run \`npm run voice:manifest\`.\n\n`;
    for (const [c, lines] of byChar) {
      md += `## ${m.CHARACTER_NAMES[c]} (\`${c}\`)\n\n${m.CHARACTER_DIRECTION[c]}\n\n| ✓ | Order | Line id | Bangla line | Emotion | Priority | File |\n|---|---|---|---|---|---|---|\n`;
      for (const l of lines) {
        const f = m.voiceFile(l);
        md += `| ${have.has(f) ? '✓' : ' '} | ${m.recordingPriority(l)} | \`${l.id}\` | ${l.text}${l.roughText ? `<br>*rough:* ${l.roughText}` : ''} | ${l.emotion} | ${P[l.priority]} | \`public/${f}\`${l.roughText ? `<br>\`public/${m.voiceFile(l, true)}\`` : ''} |\n`;
      }
      md += '\n';
    }
    writeFileSync('docs/VOICE_RECORDING_SCRIPT.md', md);
    console.log(`voice: wrote docs/VOICE_RECORDING_SCRIPT.md (${m.VOICE_LINES.length} lines)`);
  } finally {
    await server.close();
  }
}
