// Voice assets: scan public/assets/audio/voice/<character>/<line id>[.rough].ogg and write
// available.json (the runtime only fetches files listed there, so missing recordings never
// cause 404 noise). With --script, also regenerate docs/VOICE_RECORDING_SCRIPT.md from the
// game's own manifest (src/game/audio/voiceLines.ts), so text and recordings never drift.
// Usage: node scripts/assets/voice-manifest.mjs [--script]
import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = 'public/assets/audio/voice';
const files = [];
function walk(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(ogg|mp3|m4a)$/i.test(name)) files.push(relative('public', p).split(String.fromCharCode(92)).join('/'));
  }
}
walk(ROOT);
writeFileSync(join(ROOT, 'available.json'), JSON.stringify(files.sort(), null, 1) + '\n');
console.log(`voice: ${files.length} recorded file(s) listed in ${ROOT}/available.json`);

if (process.argv.includes('--script')) {
  const { createServer } = await import('vite');
  const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
  try {
    const m = await server.ssrLoadModule('/src/game/audio/voiceLines.ts');
    const have = new Set(files);
    const byChar = new Map();
    for (const l of m.VOICE_LINES) {
      if (!byChar.has(l.character)) byChar.set(l.character, []);
      byChar.get(l.character).push(l);
    }
    const P = ['background', 'flavour', 'warning', 'must-hear'];
    let md = `# Voice recording script (generated)\n\nGenerated by \`npm run voice:script\` from \`src/game/audio/voiceLines.ts\` — do not edit by hand.\n\n`;
    md += `**${m.VOICE_LINES.length} lines**, ${files.length} recorded. Deliver each line as a separate mono file, 48 kHz, peak −3 dBFS, ~150 ms of room tone before and after, no music or effects; encode to Ogg Vorbis q5 at the exact path given. Rough variants (\`.rough.ogg\`) only where a rough text is listed. After adding files run \`npm run voice:manifest\`.\n\n`;
    for (const [c, lines] of byChar) {
      md += `## ${m.CHARACTER_NAMES[c]} (\`${c}\`)\n\n${m.CHARACTER_DIRECTION[c]}\n\n| ✓ | Line id | Bangla line | Emotion | Priority | File |\n|---|---|---|---|---|---|\n`;
      for (const l of lines) {
        const f = m.voiceFile(l);
        md += `| ${have.has(f) ? '✓' : ' '} | \`${l.id}\` | ${l.text}${l.roughText ? `<br>*rough:* ${l.roughText}` : ''} | ${l.emotion} | ${P[l.priority]} | \`public/${f}\`${l.roughText ? `<br>\`public/${m.voiceFile(l, true)}\`` : ''} |\n`;
      }
      md += '\n';
    }
    writeFileSync('docs/VOICE_RECORDING_SCRIPT.md', md);
    console.log(`voice: wrote docs/VOICE_RECORDING_SCRIPT.md (${m.VOICE_LINES.length} lines)`);
  } finally {
    await server.close();
  }
}
